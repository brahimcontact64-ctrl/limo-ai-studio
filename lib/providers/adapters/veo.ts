/**
 * Google Veo 3.1 adapter (Gemini API, documented 2026-10-18). Asynchronous:
 *   submit  POST {base}/models/{model}:predictLongRunning   { instances:[{prompt, image?, lastFrame?, referenceImages?}], parameters:{aspectRatio, resolution, durationSeconds, numberOfVideos:1, personGeneration} }
 *           → { name: "<operation>" }
 *   poll    GET  {base}/{operation}                            → { done, response.generateVideoResponse.generatedSamples[0].video.uri, error }
 *   fetch   GET  <video uri> (x-goog-api-key, redirects followed) → MP4 bytes; kept only 2 days by Google, so LIMO copies it at once
 *
 * Constraints enforced before any call: 16:9 or 9:16 only (LIMO's 1:1 and 4:5 exports are fitted by the FFmpeg
 * renderer from the same clip — no second generation); clips of 4, 6 or 8 s (8 s with references or 1080p/4k);
 * at most 3 asset reference images (not on Lite); one video per request. Audio is always generated by Veo; LIMO
 * mixes its own narration/music during assembly.
 */
import { ProviderError, type AsyncCapabilityAdapter, type PollOutcome, type Provenance, type VideoRequest } from '../contracts.ts';
import { requestBytes, requestJson, type FetchLike } from '../http.ts';
import { sha256 } from '../provenance.ts';
import { GEMINI_BASE, GEMINI_PROVIDER } from './gemini-image.ts';

export const VEO_MODELS = {
  standard: 'veo-3.1-generate-preview',
  fast: 'veo-3.1-fast-generate-preview',
  lite: 'veo-3.1-lite-generate-preview',
} as const;
export type VeoTier = keyof typeof VEO_MODELS;
export const VEO_DURATIONS = [4, 6, 8] as const;
export const VEO_MAX_REFERENCES = 3;
/** Google deletes generated videos after 2 days. */
export const VEO_RETENTION_MS = 2 * 86_400_000;

export interface VeoConfig {
  apiKey: string;
  fetch: FetchLike;
  tier?: VeoTier;
  resolution?: '720p' | '1080p';
  /** EU/UK/CH/MENA: only "allow_adult" is permitted by Google. */
  personGeneration?: 'allow_adult' | 'allow_all';
  timeoutMs?: number;
  maxBytes?: number;
  loadAsset: (assetId: string) => Promise<{ bytes: Uint8Array; mime: string }>;
}

/** Shortest allowed clip that covers the scene (scenes longer than 8 s are held/trimmed by the renderer). */
export function veoDuration(sceneSeconds: number, needs8: boolean): 4 | 6 | 8 {
  if (needs8) return 8;
  return (VEO_DURATIONS.find((d) => d >= Math.min(8, Math.ceil(sceneSeconds))) ?? 8) as 4 | 6 | 8;
}

/** LIMO aspect → Veo aspect (only 16:9 and 9:16 exist; square and 4:5 are cut from 9:16 by the renderer). */
export const veoAspect = (aspect: VideoRequest['aspect']): '16:9' | '9:16' => (aspect === '16:9' ? '16:9' : '9:16');

export function veoPlan(r: VideoRequest, cfg: Pick<VeoConfig, 'tier' | 'resolution'>) {
  const tier = cfg.tier ?? 'fast';
  const refs = r.references.flatMap((x) => x.assetIds);
  if (refs.length > VEO_MAX_REFERENCES) throw new ProviderError('invalid_request', `at most ${VEO_MAX_REFERENCES} reference images`);
  if (refs.length > 0 && tier === 'lite') throw new ProviderError('invalid_request', 'Veo Lite does not accept reference images');
  // lastFrame "must be used in combination with the image parameter" (docs); combining it with reference images is not
  // documented, so LIMO does not send both.
  if (r.lastFrameAssetId && !r.firstFrameAssetId) throw new ProviderError('invalid_request', 'a last frame needs a first frame');
  if (r.lastFrameAssetId && refs.length > 0) throw new ProviderError('invalid_request', 'use either reference images or first + last frame');
  const resolution = cfg.resolution ?? '720p';
  const seconds = veoDuration(r.durationSeconds, refs.length > 0 || resolution !== '720p');
  return { model: VEO_MODELS[tier], tier, aspect: veoAspect(r.aspect), resolution, seconds, refs };
}

interface Operation {
  name?: string;
  done?: boolean;
  error?: { code?: number; message?: string };
  response?: { generateVideoResponse?: { generatedSamples?: Array<{ video?: { uri?: string } }> } };
}

const refine = (status: number, body: string) => (status === 400 && /safety|blocked|person|policy|prohibited/i.test(body) ? 'content_refused' : null);
const imageField = (a: { bytes: Uint8Array; mime: string }) => ({ inlineData: { mimeType: a.mime, data: Buffer.from(a.bytes).toString('base64') } });

export function veoAdapter(cfg: VeoConfig): AsyncCapabilityAdapter<VideoRequest> {
  const tier = cfg.tier ?? 'fast';
  const headers = { 'content-type': 'application/json', 'x-goog-api-key': cfg.apiKey };
  return {
    provider: GEMINI_PROVIDER, model: VEO_MODELS[tier], capability: 'video', paid: true, locales: ['en', 'fr', 'ar', 'de'],
    estimateUsage: (r) => ({ videoSeconds: veoPlan(r, cfg).seconds }),
    async submit(r, signal) {
      const p = veoPlan(r, cfg);
      const instance: Record<string, unknown> = { prompt: r.prompt };
      if (r.firstFrameAssetId) instance.image = imageField(await cfg.loadAsset(r.firstFrameAssetId));
      if (r.lastFrameAssetId) instance.lastFrame = imageField(await cfg.loadAsset(r.lastFrameAssetId));
      if (p.refs.length) instance.referenceImages = await Promise.all(p.refs.map(async (id) => ({ image: imageField(await cfg.loadAsset(id)), referenceType: 'asset' })));
      const parameters = {
        aspectRatio: p.aspect, resolution: p.resolution, durationSeconds: String(p.seconds), numberOfVideos: 1,
        personGeneration: r.firstFrameAssetId || p.refs.length ? 'allow_adult' : (cfg.personGeneration ?? 'allow_adult'),
      };
      const op = await requestJson<Operation>(cfg.fetch, `${GEMINI_BASE}/models/${p.model}:predictLongRunning`, {
        method: 'POST', headers, body: JSON.stringify({ instances: [instance], parameters }), timeoutMs: cfg.timeoutMs ?? 60_000, signal,
      }, refine);
      if (!op.name) throw new ProviderError('unknown', 'Veo returned no operation name');
      return { taskId: op.name, pollAfterMs: 15_000, plan: { model: p.model, seconds: p.seconds, aspect: p.aspect, resolution: p.resolution } };
    },
    async poll(taskId, signal): Promise<PollOutcome> {
      // Only Veo operation names (models/<model>/operations/<id>): no path traversal with the API key header.
      if (!/^(models\/[A-Za-z0-9.-]+\/)?operations\/[A-Za-z0-9_-]+$/.test(taskId)) throw new ProviderError('invalid_request', 'invalid operation name');
      const op = await requestJson<Operation>(cfg.fetch, `${GEMINI_BASE}/${taskId}`, { method: 'GET', headers, timeoutMs: cfg.timeoutMs ?? 30_000, signal }, refine);
      if (!op.done) return { status: 'running' };
      if (op.error) return { status: 'failed', error: new ProviderError(/safety|policy|block/i.test(op.error.message ?? '') ? 'content_refused' : 'unknown', `Veo: ${op.error.message ?? op.error.code}`) };
      const uri = op.response?.generateVideoResponse?.generatedSamples?.[0]?.video?.uri;
      // No video without an error: Google blocked the output (blocked videos are not charged).
      if (!uri) return { status: 'failed', error: new ProviderError('content_refused', 'Veo returned no video (blocked by the provider; not charged)') };
      return { status: 'succeeded', outputRef: uri };
    },
    async fetchResult(r, outputRef, plan, signal) {
      if (!/^https:\/\/generativelanguage\.googleapis\.com\//.test(outputRef)) throw new ProviderError('invalid_request', 'unexpected video URL host');
      const file = await requestBytes(cfg.fetch, outputRef, { method: 'GET', headers: { 'x-goog-api-key': cfg.apiKey }, timeoutMs: cfg.timeoutMs ?? 120_000, signal }, cfg.maxBytes ?? 200 * 1024 * 1024);
      const prov: Provenance = {
        capability: 'video', provider: GEMINI_PROVIDER, model: String(plan.model), modelVersion: null, requestKey: r.requestKey, promptSha256: sha256(r.prompt),
        inputAssetIds: [r.firstFrameAssetId, r.lastFrameAssetId].filter((x): x is string => !!x), referenceAssetIds: r.references.flatMap((x) => x.assetIds),
        characterSpecVersions: Object.fromEntries(r.references.map((x) => [x.character, x.specVersion])), approvedBy: null,
        createdAt: new Date().toISOString(), costMicros: null, currency: null, aiGenerated: true, contentCredentials: 'SynthID', mock: false, providerRequestId: null,
      };
      return { files: [{ bytes: file.bytes, mime: file.mime === 'application/octet-stream' ? 'video/mp4' : file.mime, role: 'video' }], usage: { videoSeconds: Number(plan.seconds) }, provenance: prov };
    },
  };
}
